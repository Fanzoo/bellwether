import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { describe, test } from 'node:test';
import { dragEvent, idleDrag } from '../shell/src/player/drag.mjs';
import { dropHome, familyHomes, homesWithDrops } from '../shell/src/player/layout.mjs';
import { AGENT_DIR } from './helpers.mjs';

// Independent M12 checks (tester): randomised properties of the layout, and pins on the
// permission surface. Deterministic: a seeded generator.
function rng(seed) {
  let s = seed >>> 0;
  return () => ((s = (Math.imul(s, 1664525) + 1013904223) >>> 0) / 2 ** 32);
}

describe('M12 tester: dropHome properties', () => {
  test('whatever is dropped where: on the strip, clear of every other reach unless noRoom, never moves the others', () => {
    const r = rng(12);
    for (let i = 0; i < 3000; i++) {
      const stripWidth = 400 + Math.floor(r() * 2000);
      const extent = { left: 20 + r() * 80, right: 20 + r() * 140 };
      const n = Math.floor(r() * 6);
      const others = Array.from({ length: n }, () => {
        const lo = r() * stripWidth, w = 30 + r() * 300;
        return { lo, hi: lo + w };
      });
      const snapshot = JSON.stringify(others);
      const drop = { centre: -200 + r() * (stripWidth + 400), extent, dir: r() < 0.5 ? -1 : 1 };
      const h = dropHome(drop, others, { stripWidth, wanderMax: 120 });
      assert.equal(JSON.stringify(others), snapshot, 'others untouched');
      assert.ok(Number.isFinite(h.centre) && h.wander >= 0 && h.wander <= 120, JSON.stringify([drop, h]));
      if (!h.noRoom && stripWidth >= extent.left + extent.right) {
        const lo = h.centre - h.wander - extent.left, hi = h.centre + h.wander + extent.right;
        assert.ok(h.centre - extent.left >= -0.5 && h.centre + extent.right <= stripWidth + 0.5, `on the strip ${JSON.stringify([drop, others, h])}`);
        for (const o of others) assert.ok(hi <= o.lo + 0.5 || lo >= o.hi - 0.5, `overlap ${JSON.stringify([drop, others, h, stripWidth])}`);
      }
    }
  });

  test('an invalid reach (NaN) in the others never throws or poisons the result', () => {
    const h = dropHome({ centre: 300, extent: { left: 30, right: 30 }, dir: 1 }, [{ lo: NaN, hi: 5 }, null, {}], { stripWidth: 800, wanderMax: 100 });
    assert.ok(Number.isFinite(h.centre));
  });

  test('a ghost drop (same monitor) never moves a slotted family, wherever it lands, over random layouts', () => {
    const r = rng(7);
    const layout = { stripWidth: 1400, slotWidth: 140, wanderMax: 120, dock: null };
    for (let i = 0; i < 300; i++) {
      const fams = Array.from({ length: 2 + Math.floor(r() * 5) }, (_, k) => ({ id: `f${k}`, slot: k, extent: { left: 38, right: 38 + (r() < 0.3 ? 40 : 0) } }));
      const base = familyHomes(fams, layout);
      const k = Math.floor(r() * fams.length);
      const withDrop = fams.map((f, j) => (j === k ? { ...f, drop: { centre: r() * 1500 - 50, seq: 1, ghost: true, dir: 1 } } : f));
      const after = homesWithDrops(withDrop, layout);
      for (const f of fams) if (f.id !== `f${k}`) assert.deepEqual(after.get(f.id), base.get(f.id), `${f.id} moved when f${k} was dropped`);
    }
  });
});

describe('M12 tester: gesture edges', () => {
  const step = (s, ev) => dragEvent(s, ev);
  test('once lifted, moving back inside the threshold stays a drag; release is a drop', () => {
    let r = step(idleDrag(), { type: 'down', id: 's', button: 0, x: 100, y: 10, left: 80 });
    r = step(r.state, { type: 'move', x: 130, y: 10 });
    assert.ok(r.actions.some((a) => a.do === 'lift'));
    r = step(r.state, { type: 'move', x: 101, y: 10 });
    assert.deepEqual(r.actions.map((a) => a.do), ['carry']);
    r = step(r.state, { type: 'up', x: 101, y: 10 });
    assert.deepEqual(r.actions.map((a) => a.do), ['drop']);
  });
  test('non-finite coordinates never throw', () => {
    let r = step(idleDrag(), { type: 'down', id: 's', button: 0, x: 1, y: 1, left: 0 });
    r = step(r.state, { type: 'move', x: NaN, y: Infinity });
    assert.ok(r.state);
  });
});

describe('M12 tester: the permission surface', () => {
  const cap = (n) => JSON.parse(fs.readFileSync(path.join(AGENT_DIR, 'shell/src-tauri/capabilities', n), 'utf8'));
  test('sprite_drag is granted to strip-* only; the setup window is not given it', () => {
    assert.ok(cap('strip.json').permissions.includes('allow-sprite-drag'));
    assert.ok(!cap('onboarding.json').permissions.some((p) => /sprite-drag/.test(p)));
    assert.deepEqual(cap('strip.json').windows, ['strip-*']);
  });
  test('the generated permission file defines allow and deny for exactly this command', () => {
    const t = fs.readFileSync(path.join(AGENT_DIR, 'shell/src-tauri/permissions/autogenerated/sprite_drag.toml'), 'utf8');
    assert.match(t, /commands\.allow = \["sprite_drag"\]/);
    assert.match(t, /commands\.deny = \["sprite_drag"\]/);
  });
  test('nothing persists a drop: Places.dropped is never written to a file, state or report', () => {
    const lib = fs.readFileSync(path.join(AGENT_DIR, 'shell/src-tauri/src/lib.rs'), 'utf8');
    const sprite = lib.slice(lib.indexOf('fn sprite_drag('), lib.indexOf('fn shell_log'));
    assert.ok(!/shellstate|fs::write|placed_report|report_placed|\.json"/.test(sprite), 'sprite_drag writes nothing');
  });
});
