import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { describe, test } from 'node:test';
import { compile, evaluate, KEYWORDS } from '../shell/src/player/expr.mjs';
import { AGENT_DIR } from './helpers.mjs';

/**
 * Tester probes for Milestone 3. No window is opened here and nothing touches
 * ~/Library/LaunchAgents or launchctl. (The repository's LaunchAgent autostart went with the
 * Node brain in milestone 11; the eSheep fetch probes now test scripts/fetch-pets.mjs, in
 * pets.test.mjs.)
 */

const TAURI = path.join(AGENT_DIR, 'shell', 'src-tauri');
const SRC = path.join(AGENT_DIR, 'shell', 'src');
const read = (f) => fs.readFileSync(f, 'utf8');

describe('webview surface', () => {
  test('the seven strip commands (sprite_drag since milestone 12) and the eleven onboarding commands are the only commands: handler list, build.rs, autogenerated permissions and the two capabilities agree', () => {
    const lib = read(path.join(TAURI, 'src', 'lib.rs'));
    const handler = /generate_handler!\[([^\]]+)\]/.exec(lib)[1].split(',').map((s) => s.trim().replace(/^onboarding::/, '')).filter(Boolean).sort();
    const build = [...read(path.join(TAURI, 'build.rs')).matchAll(/"([a-z_]+)"/g)].map((m) => m[1]).sort();
    const granted = (f) => JSON.parse(read(path.join(TAURI, 'capabilities', f))).permissions.map((p) => p.replace(/^allow-/, '').replace(/-/g, '_')).sort();
    const strip = granted('strip.json');
    const onboarding = granted('onboarding.json');
    assert.deepEqual(handler, build);
    assert.deepEqual(handler, [...strip, ...onboarding].sort());
    assert.equal(strip.length, 7);
    assert.equal(onboarding.length, 11);
    assert.ok(!strip.some((c) => onboarding.includes(c)), 'no command is granted to both');
    assert.deepEqual(JSON.parse(read(path.join(TAURI, 'capabilities', 'strip.json'))).windows, ['strip-*']);
    assert.deepEqual(JSON.parse(read(path.join(TAURI, 'capabilities', 'onboarding.json'))).windows, ['onboarding']);
    for (const c of handler) {
      const toml = read(path.join(TAURI, 'permissions', 'autogenerated', `${c}.toml`));
      assert.match(toml, new RegExp(`commands.allow = \\["${c}"\\]`));
      assert.doesNotMatch(toml, /\[permission\.scope|fs:|shell:/);
    }
    assert.deepEqual(fs.readdirSync(path.join(TAURI, 'permissions', 'autogenerated')).length, 18);
    const resolved = fs.existsSync(path.join(TAURI, 'gen', 'schemas', 'capabilities.json')) ? JSON.parse(read(path.join(TAURI, 'gen', 'schemas', 'capabilities.json'))) : null;
    if (resolved) {
      assert.deepEqual(Object.keys(resolved).sort(), ['onboarding', 'strip']);
      assert.equal(resolved.strip.permissions.length, 7);
      assert.equal(resolved.onboarding.permissions.length, 11);
    }
    for (const f of ['strip.json', 'onboarding.json']) assert.ok(!JSON.parse(read(path.join(TAURI, 'capabilities', f))).permissions.some((p) => /:/.test(p)), `${f}: a namespaced plugin or core permission is granted`);
  });

  test('the config opens no other doors: no remote IPC, no asset protocol, no devtools feature, no shell/fs plugins, one .plugin()', () => {
    const conf = JSON.parse(read(path.join(TAURI, 'tauri.conf.json')));
    const sec = conf.app.security;
    for (const k of Object.keys(sec)) assert.ok(['csp', 'capabilities'].includes(k), `unexpected security key ${k}`);
    assert.equal(conf.plugins, undefined);
    assert.equal(conf.build.devUrl, undefined);
    assert.ok(!/^https?:/.test(conf.build.frontendDist));
    const cargo = read(path.join(TAURI, 'Cargo.toml'));
    assert.doesNotMatch(cargo, /devtools|protocol-asset|unstable|isolation|image-png|macos-private-api/);
    // M7-4: exactly one tauri feature is allowed, tray-icon (the menu-bar menu, handled in Rust).
    const tauriLine = /^tauri = \{[^}]*\}/m.exec(cargo)[0];
    assert.deepEqual([...tauriLine.matchAll(/features = \[([^\]]*)\]/g)].flatMap((m) => m[1].split(',').map((x) => x.trim().replace(/"/g, '')).filter(Boolean)), ['tray-icon']);
    // the tray menu is Rust-only: it adds no command, no capability and no webview-reachable IPC.
    const tray = fs.readFileSync(path.join(TAURI, 'src', 'tray.rs'), 'utf8').replace(/\/\/.*$/gm, '');
    assert.doesNotMatch(tray, /#\[tauri::command\]|invoke_handler|\.emit\(|eval|Command::new|std::process|fs::(remove|write)|LaunchAgents/);
    const ids = [...tray.matchAll(/with_id\(app, "([a-z]+)"/g)].map((m) => m[1]);
    // M7: "setup" (Set up Bellwether…) only opens the onboarding window, from Rust.
    // M9: "updates" (Check for Updates…) only asks updater.rs to check, from Rust.
    assert.deepEqual(ids, ['mute', 'hide', 'labels', 'quit', 'setup', 'updates']);
    // the strip's seven commands stay seven; the onboarding window's eleven live in onboarding.rs
    assert.equal([...fs.readFileSync(path.join(TAURI, 'src', 'lib.rs'), 'utf8').matchAll(/#\[tauri::command\]/g)].length, 7);
    assert.equal([...fs.readFileSync(path.join(TAURI, 'src', 'onboarding.rs'), 'utf8').matchAll(/#\[tauri::command\]/g)].length, 11);
    const lib = read(path.join(TAURI, 'src', 'lib.rs'));
    // M9: two plugins, single-instance and (only in a build that updates itself) the updater.
    assert.equal([...lib.matchAll(/\.plugin\(/g)].length, 2);
    assert.match(lib, /if updates_on \{\s*builder = builder\.plugin\(tauri_plugin_updater::Builder::new\(\)\.build\(\)\);\s*\}/);
    assert.equal(fs.readdirSync(path.join(TAURI, 'capabilities')).sort().join(), 'onboarding.json,strip.json');
    // Every source file, src/bin/ (the Windows console CLI, W2) included.
    for (const f of fs.readdirSync(path.join(TAURI, 'src'), { recursive: true }).filter((n) => n.endsWith('.rs'))) {
      const s = read(path.join(TAURI, 'src', f));
      assert.doesNotMatch(s, /\beval_script\b|\bevaluate_script\b|\bopen_devtools\b|\bon_navigation\b|WebviewUrl::External/, `${f}`);
      // M5-1: with_webview is allowed in exactly one place (strips.rs), and only to hand the
      // native view to the guarded occlusion switch; nowhere else may reach the native view.
      const uses = [...s.matchAll(/\bwith_webview\b/g)].length;
      if (f === 'strips.rs') {
        assert.equal(uses, 1, 'strips.rs may call with_webview exactly once');
        const at = s.indexOf('with_webview');
        const block = s.slice(at, at + 400);
        assert.match(block, /keep_page_visible\(wv\.inner\(\)\)/);
        assert.doesNotMatch(block, /evaluate|eval|navigate|load_url/);
        const fn = s.slice(s.indexOf('fn keep_page_visible'));
        assert.match(fn, /respondsToSelector:/);
        assert.ok(fn.indexOf('respondsToSelector:') < fn.indexOf('_setWindowOcclusionDetectionEnabled:') + 200);
        assert.match(fn, /if !send_sel\(webview, sel_responds, sel_setter\) \{\s*return false;/);
        assert.match(fn, /is_null\(\)/);
        assert.equal([...fn.matchAll(/CString::new\("(_[a-zA-Z]+:)"\)/g)].map((m) => m[1]).filter((x, i, a) => a.indexOf(x) === i).join(), '_setWindowOcclusionDetectionEnabled:', 'only one private selector is used');
      } else {
        assert.equal(uses, 0, `${f} must not call with_webview`);
      }
    }
  });

  test('the webview source has no eval, Function, innerHTML, remote URL, fetch, XHR, WebSocket or dynamic import', () => {
    const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));
    for (const f of walk(SRC)) {
      const s = read(f);
      assert.doesNotMatch(s.replace(/\/\/.*$/gm, '').replace(/\/\*[\s\S]*?\*\//g, ''), /\beval\s*\(|new\s+Function|\bFunction\s*\(|innerHTML|outerHTML|insertAdjacentHTML|document\.write|\bfetch\s*\(|XMLHttpRequest|WebSocket|EventSource|\bimport\s*\(|https?:\/\/|setTimeout\s*\(\s*['"`]|setInterval\s*\(\s*['"`]/, f);
    }
  });

  test('debug_snapshot refuses without --snapshot, filters its suffix, and checks for PNG magic', () => {
    const lib = read(path.join(TAURI, 'src', 'lib.rs'));
    const fn = lib.slice(lib.indexOf('fn debug_snapshot'), lib.indexOf('fn decode_base64'));
    assert.match(fn, /let Some\(\(path, _\)\) = shared\.snapshot\.as_ref\(\) else \{ return Err/);
    assert.ok(fn.indexOf('as_ref()') < fn.indexOf('fs::write'), 'the refusal comes before any write');
    assert.match(fn, /is_ascii_alphanumeric\(\) \|\| \*c == '-'/);
    assert.match(fn, /starts_with\(b"\\x89PNG"\)/);
    assert.match(lib, /snapshot: flags\.snapshot\.clone\(\)/);
  });
});

describe('the pet expression evaluator cannot run code', () => {
  const env = { screenW: 1000, screenH: 100, areaW: 1000, areaH: 100, imageW: 40, imageH: 40, imageX: 5, imageY: 5, random: 0.5, randS: 1 };
  const hostile = [
    "constructor.constructor('globalThis.__pwned=1')()",
    'alert(1)',
    '__proto__',
    'this',
    'globalThis',
    '(1)(2)',
    '1;globalThis.__pwned=1',
    'a=1',
    '`${globalThis.__pwned=1}`',
    '1,2',
    '1?2:3',
    '1<2',
    '1**2',
    '2**1000',
    '1e999',
    '0x10',
    '1_000',
    '.',
    '..',
    '1..2',
    '1.2.3',
    'random()',
    'random.x',
    'random[0]',
    'imageW imageH',
    '\u0661\u0662',
    'ｉｍａｇｅＷ',
    '1 /* c */ + 2',
    'void 0',
    'typeof 1',
    "'a'+'b'",
    '"a"',
    '1+',
    '()',
    ')(',
    '(((',
    '-'.repeat(199),
    '('.repeat(100) + '1' + ')'.repeat(100),
    '('.repeat(150) + '1',
    '1+'.repeat(99) + '1',
    'x'.repeat(5000),
    '1/0',
    '0/0',
    '-1/0',
    '1/0.0000000000000000000000000000001*1e300',
    'screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW',
    '\u0000',
    '1\u202e+2',
    'randS+random\n+1',
  ];
  test('hostile expressions return a finite number, never throw, never execute', () => {
    delete globalThis.__pwned;
    const warnings = [];
    for (const e of hostile) {
      let v;
      assert.doesNotThrow(() => (v = evaluate(e, env, (w) => warnings.push(w))), JSON.stringify(e.slice(0, 40)));
      assert.ok(Number.isFinite(v), `${JSON.stringify(e.slice(0, 40))} -> ${v}`);
    }
    assert.equal(globalThis.__pwned, undefined);
    assert.equal(evaluate("constructor.constructor('return 7')()", env), 0);
    assert.equal(evaluate('alert(1)', env), 0);
    assert.ok(warnings.length >= 20);
  });
  test('a hostile env cannot smuggle values in: missing, NaN, Infinity, string and object keywords evaluate as 0', () => {
    for (const bad of [undefined, NaN, Infinity, '5', { valueOf: () => 5 }, [5], null]) assert.equal(evaluate('imageW+1', { imageW: bad }), 1);
  });
  test('differential fuzz: valid arithmetic agrees with JavaScript, anything else is 0', () => {
    let seed = 12345;
    const rnd = () => ((seed = (seed * 1664525 + 1013904223) >>> 0) / 2 ** 32);
    const gen = (d) => {
      const r = rnd();
      if (d <= 0 || r < 0.25) return rnd() < 0.3 ? KEYWORDS[Math.floor(rnd() * 8)] : String(Math.floor(rnd() * 50));
      if (r < 0.4) return `(${gen(d - 1)})`;
      if (r < 0.5) return `-(${gen(d - 1)})`;
      return `${gen(d - 1)} ${'+-*'[Math.floor(rnd() * 3)]} ${gen(d - 1)}`;
    };
    for (let i = 0; i < 3000; i++) {
      const src = gen(4);
      const ref = new Function(...Object.keys(env), `return (${src});`)(...Object.values(env));
      const got = evaluate(src, env);
      assert.ok(Math.abs(got - ref) < 1e-6 * Math.max(1, Math.abs(ref)), `${src}: ${got} vs ${ref}`);
    }
    let junk = 0;
    const alphabet = '()+-*/. 0123456789abcdefgimnrsxyzWHXYAIS_[]{}\'";,=<>!&|?:\\`$@#%^~\u0000\u202e';
    for (let i = 0; i < 20000; i++) {
      let s = '';
      for (let k = rnd() * 40; k > 0; k--) s += alphabet[Math.floor(rnd() * alphabet.length)];
      const v = evaluate(s, env);
      assert.ok(Number.isFinite(v));
      junk++;
    }
    assert.equal(junk, 20000);
  });
  test('compile of a 200-character nest and a long chain returns within a few ms (no recursion bomb)', () => {
    const t = process.hrtime.bigint();
    for (const s of ['('.repeat(99) + '1' + ')'.repeat(99), '-'.repeat(199) + '1', '1' + '+1'.repeat(99)]) compile(s);
    assert.ok(Number(process.hrtime.bigint() - t) / 1e6 < 100);
  });
});
