describe('webview surface', () => {
  test('the six strip commands and the eleven onboarding commands are the only commands: handler list, build.rs, autogenerated permissions and the two capabilities agree', () => {
    const lib = read(path.join(TAURI, 'src', 'lib.rs'));
    const handler = /generate_handler!\[([^\]]+)\]/.exec(lib)[1].split(',').map((s) => s.trim().replace(/^onboarding::/, '')).filter(Boolean).sort();
    const build = [...read(path.join(TAURI, 'build.rs')).matchAll(/"([a-z_]+)"/g)].map((m) => m[1]).sort();
    const granted = (f) => JSON.parse(read(path.join(TAURI, 'capabilities', f))).permissions.map((p) => p.replace(/^allow-/, '').replace(/-/g, '_')).sort();
    const strip = granted('strip.json');
    const onboarding = granted('onboarding.json');
    assert.deepEqual(handler, build);
    assert.deepEqual(handler, [...strip, ...onboarding].sort());
    assert.equal(strip.length, 6);
    assert.equal(onboarding.length, 11);
    assert.ok(!strip.some((c) => onboarding.includes(c)), 'no command is granted to both');
    assert.deepEqual(JSON.parse(read(path.join(TAURI, 'capabilities', 'strip.json'))).windows, ['strip-*']);
    assert.deepEqual(JSON.parse(read(path.join(TAURI, 'capabilities', 'onboarding.json'))).windows, ['onboarding']);
    for (const c of handler) {
      const toml = read(path.join(TAURI, 'permissions', 'autogenerated', `${c}.toml`));
      assert.match(toml, new RegExp(`commands.allow = \\["${c}"\\]`));
      assert.doesNotMatch(toml, /\[permission\.scope|fs:|shell:/);
    }
    assert.deepEqual(fs.readdirSync(path.join(TAURI, 'permissions', 'autogenerated')).length, 17);
    const resolved = fs.existsSync(path.join(TAURI, 'gen', 'schemas', 'capabilities.json')) ? JSON.parse(read(path.join(TAURI, 'gen', 'schemas', 'capabilities.json'))) : null;
    if (resolved) {
      assert.deepEqual(Object.keys(resolved).sort(), ['onboarding', 'strip']);
      assert.equal(resolved.strip.permissions.length, 6);
      assert.equal(resolved.onboarding.permissions.length, 11);
    }
    for (const f of ['strip.json', 'onboarding.json']) assert.ok(!JSON.parse(read(path.join(TAURI, 'capabilities', f))).permissions.some((p) => /:/.test(p)), `${f}: a namespaced plugin or core permission is granted`);
  });

  test('the config opens no other doors: no remote IPC, no asset protocol, no devtools feature, no shell/fs plugins, one .plugin()', () => {
    const conf = JSON.parse(read(path.join(TAURI, 'tauri.conf.json')));
    const sec = conf.app.security;
    for (const k of Object.keys(sec)) assert.ok(['csp', 'capabilities'].includes(k), `unexpected security key ${k}`);
    assert.equal(conf.plugins, undefined);
    assert.equal(conf.build.devUrl, undefined);
    assert.ok(!/^https?:/.test(conf.build.frontendDist));
    const cargo = read(path.join(TAURI, 'Cargo.toml'));
    assert.doesNotMatch(cargo, /devtools|protocol-asset|unstable|isolation|image-png|macos-private-api/);
    // M7-4: exactly one tauri feature is allowed, tray-icon (the menu-bar menu, handled in Rust).
    const tauriLine = /^tauri = \{[^}]*\}/m.exec(cargo)[0];
    assert.deepEqual([...tauriLine.matchAll(/features = \[([^\]]*)\]/g)].flatMap((m) => m[1].split(',').map((x) => x.trim().replace(/"/g, '')).filter(Boolean)), ['tray-icon']);
    // the tray menu is Rust-only: it adds no command, no capability and no webview-reachable IPC.
    const tray = fs.readFileSync(path.join(TAURI, 'src', 'tray.rs'), 'utf8').replace(/\/\/.*$/gm, '');
    assert.doesNotMatch(tray, /#\[tauri::command\]|invoke_handler|\.emit\(|eval|Command::new|std::process|fs::(remove|write)|LaunchAgents/);
    const ids = [...tray.matchAll(/with_id\(app, "([a-z]+)"/g)].map((m) => m[1]);
    // M7: "setup" (Set up Bellwether…) only opens the onboarding window, from Rust.
    // M9: "updates" (Check for Updates…) only asks updater.rs to check, from Rust.
    assert.deepEqual(ids, ['mute', 'hide', 'labels', 'quit', 'setup', 'updates']);
    // the strip's six commands stay six; the onboarding window's eleven live in onboarding.rs
    assert.equal([...fs.readFileSync(path.join(TAURI, 'src', 'lib.rs'), 'utf8').matchAll(/#\[tauri::command\]/g)].length, 6);
    assert.equal([...fs.readFileSync(path.join(TAURI, 'src', 'onboarding.rs'), 'utf8').matchAll(/#\[tauri::command\]/g)].length, 11);
    const lib = read(path.join(TAURI, 'src', 'lib.rs'));
    // M9: two plugins, single-instance and (only in a build that updates itself) the updater.
    assert.equal([...lib.matchAll(/\.plugin\(/g)].length, 2);
    assert.match(lib, /if updates_on \{\s*builder = builder\.plugin\(tauri_plugin_updater::Builder::new\(\)\.build\(\)\);\s*\}/);
    assert.equal(fs.readdirSync(path.join(TAURI, 'capabilities')).sort().join(), 'onboarding.json,strip.json');
    for (const f of fs.readdirSync(path.join(TAURI, 'src'))) {
      const s = read(path.join(TAURI, 'src', f));
      assert.doesNotMatch(s, /\beval_script\b|\bevaluate_script\b|\bopen_devtools\b|\bon_navigation\b|WebviewUrl::External/, `${f}`);
      // M5-1: with_webview is allowed in exactly one place (strips.rs), and only to hand the
      // native view to the guarded occlusion switch; nowhere else may reach the native view.
      const uses = [...s.matchAll(/\bwith_webview\b/g)].length;
      if (f === 'strips.rs') {
        assert.equal(uses, 1, 'strips.rs may call with_webview exactly once');
        const at = s.indexOf('with_webview');
        const block = s.slice(at, at + 400);
        assert.match(block, /keep_page_visible\(wv\.inner\(\)\)/);
        assert.doesNotMatch(block, /evaluate|eval|navigate|load_url/);
        const fn = s.slice(s.indexOf('fn keep_page_visible'));
        assert.match(fn, /respondsToSelector:/);
        assert.ok(fn.indexOf('respondsToSelector:') < fn.indexOf('_setWindowOcclusionDetectionEnabled:') + 200);
        assert.match(fn, /if !send_sel\(webview, sel_responds, sel_setter\) \{\s*return false;/);
        assert.match(fn, /is_null\(\)/);
        assert.equal([...fn.matchAll(/CString::new\("(_[a-zA-Z]+:)"\)/g)].map((m) => m[1]).filter((x, i, a) => a.indexOf(x) === i).join(), '_setWindowOcclusionDetectionEnabled:', 'only one private selector is used');
      } else {
        assert.equal(uses, 0, `${f} must not call with_webview`);
      }
    }
  });

  test('the webview source has no eval, Function, innerHTML, remote URL, fetch, XHR, WebSocket or dynamic import', () => {
    const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));
    for (const f of walk(SRC)) {
      const s = read(f);
      assert.doesNotMatch(s.replace(/\/\/.*$/gm, '').replace(/\/\*[\s\S]*?\*\//g, ''), /\beval\s*\(|new\s+Function|\bFunction\s*\(|innerHTML|outerHTML|insertAdjacentHTML|document\.write|\bfetch\s*\(|XMLHttpRequest|WebSocket|EventSource|\bimport\s*\(|https?:\/\/|setTimeout\s*\(\s*['"`]|setInterval\s*\(\s*['"`]/, f);
    }
  });

  test('debug_snapshot refuses without --snapshot, filters its suffix, and checks for PNG magic', () => {
    const lib = read(path.join(TAURI, 'src', 'lib.rs'));
    const fn = lib.slice(lib.indexOf('fn debug_snapshot'), lib.indexOf('fn decode_base64'));
    assert.match(fn, /let Some\(\(path, _\)\) = shared\.snapshot\.as_ref\(\) else \{ return Err/);
    assert.ok(fn.indexOf('as_ref()') < fn.indexOf('fs::write'), 'the refusal comes before any write');
    assert.match(fn, /is_ascii_alphanumeric\(\) \|\| \*c == '-'/);
    assert.match(fn, /starts_with\(b"\\x89PNG"\)/);
    assert.match(lib, /snapshot: flags\.snapshot\.clone\(\)/);
  });
});

describe('the pet expression evaluator cannot run code', () => {
  const env = { screenW: 1000, screenH: 100, areaW: 1000, areaH: 100, imageW: 40, imageH: 40, imageX: 5, imageY: 5, random: 0.5, randS: 1 };
  const hostile = [
    "constructor.constructor('globalThis.__pwned=1')()",
    'alert(1)',
    '__proto__',
    'this',
    'globalThis',
    '(1)(2)',
    '1;globalThis.__pwned=1',
    'a=1',
    '`${globalThis.__pwned=1}`',
    '1,2',
    '1?2:3',
    '1<2',
    '1**2',
    '2**1000',
    '1e999',
    '0x10',
    '1_000',
    '.',
    '..',
    '1..2',
    '1.2.3',
    'random()',
    'random.x',
    'random[0]',
    'imageW imageH',
    '\u0661\u0662',
    'ｉｍａｇｅＷ',
    '1 /* c */ + 2',
    'void 0',
    'typeof 1',
    "'a'+'b'",
    '"a"',
    '1+',
    '()',
    ')(',
    '(((',
    '-'.repeat(199),
    '('.repeat(100) + '1' + ')'.repeat(100),
    '('.repeat(150) + '1',
    '1+'.repeat(99) + '1',
    'x'.repeat(5000),
    '1/0',
    '0/0',
    '-1/0',
    '1/0.0000000000000000000000000000001*1e300',
    'screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW*screenW',
    '\u0000',
    '1\u202e+2',
    'randS+random\n+1',
  ];
  test('hostile expressions return a finite number, never throw, never execute', () => {
    delete globalThis.__pwned;
    const warnings = [];
    for (const e of hostile) {
      let v;
      assert.doesNotThrow(() => (v = evaluate(e, env, (w) => warnings.push(w))), JSON.stringify(e.slice(0, 40)));
      assert.ok(Number.isFinite(v), `${JSON.stringify(e.slice(0, 40))} -> ${v}`);
    }
    assert.equal(globalThis.__pwned, undefined);
    assert.equal(evaluate("constructor.constructor('return 7')()", env), 0);
    assert.equal(evaluate('alert(1)', env), 0);
    assert.ok(warnings.length >= 20);
  });
  test('a hostile env cannot smuggle values in: missing, NaN, Infinity, string and object keywords evaluate as 0', () => {
    for (const bad of [undefined, NaN, Infinity, '5', { valueOf: () => 5 }, [5], null]) assert.equal(evaluate('imageW+1', { imageW: bad }), 1);
  });
  test('differential fuzz: valid arithmetic agrees with JavaScript, anything else is 0', () => {
    let seed = 12345;
    const rnd = () => ((seed = (seed * 1664525 + 1013904223) >>> 0) / 2 ** 32);
    const gen = (d) => {
      const r = rnd();
      if (d <= 0 || r < 0.25) return rnd() < 0.3 ? KEYWORDS[Math.floor(rnd() * 8)] : String(Math.floor(rnd() * 50));
      if (r < 0.4) return `(${gen(d - 1)})`;
      if (r < 0.5) return `-(${gen(d - 1)})`;
      return `${gen(d - 1)} ${'+-*'[Math.floor(rnd() * 3)]} ${gen(d - 1)}`;
    };
    for (let i = 0; i < 3000; i++) {
      const src = gen(4);
      const ref = new Function(...Object.keys(env), `return (${src});`)(...Object.values(env));
      const got = evaluate(src, env);
      assert.ok(Math.abs(got - ref) < 1e-6 * Math.max(1, Math.abs(ref)), `${src}: ${got} vs ${ref}`);
    }
    let junk = 0;
    const alphabet = '()+-*/. 0123456789abcdefgimnrsxyzWHXYAIS_[]{}\'";,=<>!&|?:\\`$@#%^~\u0000\u202e';
    for (let i = 0; i < 20000; i++) {
      let s = '';
      for (let k = rnd() * 40; k > 0; k--) s += alphabet[Math.floor(rnd() * alphabet.length)];
      const v = evaluate(s, env);
      assert.ok(Number.isFinite(v));
      junk++;
    }
    assert.equal(junk, 20000);
  });
  test('compile of a 200-character nest and a long chain returns within a few ms (no recursion bomb)', () => {
    const t = process.hrtime.bigint();
    for (const s of ['('.repeat(99) + '1' + ')'.repeat(99), '-'.repeat(199) + '1', '1' + '+1'.repeat(99)]) compile(s);
    assert.ok(Number(process.hrtime.bigint() - t) / 1e6 < 100);
  });
});

describe('autostart (temp HOME only; launchctl is never run)', notUnderRust("the repository's LaunchAgent autostart, which writes plists; the app's `autostart` drives SMAppService and never writes ~/Library/LaunchAgents (test/DIVERGENCES.md 23, shell/src-tauri/tests/no_launchagents.rs)"), () => {
  const never = () => {
    throw new Error('launchctl was called');
  };
  const mk = () => {
    const home = tempDir('as-home-');
    fs.mkdirSync(path.join(home, 'Library', 'LaunchAgents'), { recursive: true });
    return home;
  };
  test('preview writes nothing; --write writes a valid plist with no token, and never calls launchctl for a temp HOME', () => {
    const home = mk();
    const file = path.join(home, 'Library', 'LaunchAgents', 'local.bellwether.brain.plist');
    process.env.BELLWETHER_HOOK_TOKEN = 'plistTokenCanary_0123456789abcdef';
    try {
      const prev = autostart('install', { home, run: never, uid: 501 });
      assert.equal(prev.wrote, false);
      assert.equal(fs.existsSync(file), false);
      assert.match(prev.lines.join('\n'), /Preview only/);
      const w = autostart('install', { home, write: true, run: never, uid: 501 });
      assert.equal(w.wrote, true);
      const text = fs.readFileSync(file, 'utf8');
      assert.doesNotMatch(text, /plistTokenCanary|BELLWETHER_HOOK_TOKEN/);
      assert.match(w.lines.join('\n'), /launchctl not called/);
      const lint = spawnSync('plutil', ['-lint', file], { encoding: 'utf8' });
      assert.equal(lint.status, 0, lint.stdout + lint.stderr);
      assert.match(text, /<key>KeepAlive<\/key>\s*<dict>\s*<key>SuccessfulExit<\/key>\s*<false\/>/);
      const st = autostart('status', { home, run: never, uid: 501 });
      assert.match(st.lines.join('\n'), /not checked/);
      const un = autostart('uninstall', { home, write: true, run: never, uid: 501 });
      assert.equal(fs.existsSync(file), false);
      assert.match(un.lines.join('\n'), /launchctl not called/);
    } finally {
      delete process.env.BELLWETHER_HOOK_TOKEN;
    }
  });
  test('paths with XML metacharacters and spaces are escaped and the plist stays valid', () => {
    const text = plistText({ nodePath: '/opt/no de/bin/node', agentDir: '/h/a&b <c>/bellwether', dataDir: '/h/a&b <c>/data' });
    const f = path.join(tempDir('plist-'), 'x.plist');
    fs.writeFileSync(f, text);
    assert.equal(spawnSync('plutil', ['-lint', f], { encoding: 'utf8' }).status, 0);
    assert.doesNotMatch(text, /a&b <c>/);
  });
  test('a symlinked or odd HOME that is not the real home never reaches launchctl; HOME that IS real would, so the guard is checked by injection', () => {
    const home = mk();
    const link = path.join(tempDir('as-link-'), 'home-link');
    fs.symlinkSync(home, link);
    autostart('install', { home: link, write: true, run: never, uid: 501 });
    autostart('uninstall', { home: link, write: true, run: never, uid: 501 });
    const calls = [];
    autostart('install', { home, write: true, uid: 501, realHome: () => true, run: (c, a) => (calls.push([c, ...a]), { ok: true, out: '' }) });
    assert.deepEqual(calls.map((c) => c[1]), ['bootout', 'bootstrap']);
    assert.ok(calls.every((c) => c[0] === 'launchctl'));
  });
  test('the CLI under a temp HOME: install preview, --write, status and a refused unknown flag', () => {
    const home = mk();
    const env = { PATH: process.env.PATH, HOME: home, BELLWETHER_DATA_DIR: path.join(home, 'data'), BELLWETHER_HOOK_TOKEN: 'cliTokenCanary_0123456789abcdef' };
    // On a fresh clone the strip isn't built: install refuses (exit 2) and says how to
    // go on; the rest then runs with --brain-only, which needs no build.
    const built = fs.existsSync(shellBinary());
    const cli = (...a) => spawnBrainSync(['autostart', ...a], { encoding: 'utf8', env });
    if (!built) {
      const refused = cli('install', '--write');
      assert.equal(refused.status, 2, refused.stderr);
      assert.match(refused.stderr, /isn't built yet[\s\S]*--brain-only/);
      assert.ok(!fs.existsSync(path.join(home, 'Library', 'LaunchAgents', 'local.bellwether.brain.plist')), 'nothing written when refused');
    }
    const run = (...a) => cli(...a, ...(built || a[0] !== 'install' && a[0] !== 'uninstall' ? [] : ['--brain-only']));
    const p = run('install');
    assert.equal(p.status, 0, p.stderr);
    assert.doesNotMatch(p.stdout, /cliTokenCanary/);
    const w = run('install', '--write');
    assert.equal(w.status, 0, w.stderr);
    assert.match(w.stdout, /launchctl not called/);
    assert.ok(fs.existsSync(path.join(home, 'Library', 'LaunchAgents', 'local.bellwether.brain.plist')));
    assert.equal(run('install', '--writ').status, 3);
    assert.equal(run('bogus').status, 3);
    assert.equal(run('status', '--write').status, 3);
    assert.equal(run('uninstall', '--write').status, 0);
  });
});

describe('pets fetch', notUnderRust("`pets fetch` downloads the eSheep art into the repository's data/pets; the app imports a pet file instead (`pets import`, plan D8), tested in pets.test.mjs and crates/brain pets.rs"), () => {
  const GOOD = Buffer.from('<animations>good</animations>');
  const hash = (b) => createHash('sha256').update(b).digest('hex');
  const pinned = { esheep64: { path: 'Pets/esheep64/animations.xml', sha256: hash(GOOD) } };
  const resp = (body, init = {}) => async () => new Response(body, { status: 200, ...init });
  const dirs = () => tempDir('pets-');

  test('a good file is written and verified; a second run downloads nothing', async () => {
    const d = dirs();
    let n = 0;
    const f = async () => (n++, new Response(GOOD));
    await fetchPets(d, { fetchImpl: f, pinned });
    assert.equal(fs.readFileSync(path.join(d, 'pets', 'esheep64', 'animations.xml')).equals(GOOD), true);
    await fetchPets(d, { fetchImpl: f, pinned });
    assert.equal(n, 1);
  });
  test('a hash mismatch writes nothing, leaves an existing good file alone, and replaces a corrupted one only with a verified one', async () => {
    const d = dirs();
    await assert.rejects(fetchPets(d, { fetchImpl: resp('<animations>evil</animations>'), pinned }), /sha256 mismatch/);
    assert.equal(fs.existsSync(path.join(d, 'pets')), false, 'a rejected download left files behind');
    await fetchPets(d, { fetchImpl: resp(GOOD), pinned });
    const file = path.join(d, 'pets', 'esheep64', 'animations.xml');
    fs.writeFileSync(file, 'tampered');
    await fetchPets(d, { fetchImpl: resp(GOOD), pinned });
    assert.equal(fs.readFileSync(file).equals(GOOD), true);
    fs.writeFileSync(file, 'tampered');
    await assert.rejects(fetchPets(d, { fetchImpl: resp('nope'), pinned }));
    assert.equal(fs.readFileSync(file, 'utf8'), 'tampered', 'a failed download must not touch the file');
  });
  test('folder names that are not pinned pets are refused, including prototype keys and traversal', async () => {
    const d = dirs();
    for (const name of ['../evil', '..', '/etc', 'esheep64/../../x', '__proto__', 'constructor', 'toString', 'hasOwnProperty', '']) {
      let called = false;
      await assert.rejects(fetchPets(d, { only: [name], fetchImpl: async () => ((called = true), new Response(GOOD)), pinned }), /unknown pet|HTTP|mismatch/, JSON.stringify(name));
      assert.equal(called && name !== '__proto__' && name !== 'constructor' && name !== 'toString' && name !== 'hasOwnProperty', false, `${name} reached the network`);
    }
    assert.deepEqual(fs.readdirSync(d), [], 'something was written');
  });
  test('HTTP errors, a redirect to another host, and a connection that dies mid-body each give a cause, not a stack', async () => {
    const d = dirs();
    await assert.rejects(fetchPets(d, { fetchImpl: async () => new Response('x', { status: 404 }), pinned }), /HTTP 404/);
    await assert.rejects(fetchPets(d, { fetchImpl: async () => new Response('x', { status: 500 }), pinned }), /HTTP 500/);
    await assert.rejects(fetchPets(d, { fetchImpl: async () => { throw Object.assign(new TypeError('fetch failed'), { cause: { code: 'ENOTFOUND' } }); }, pinned }), /download failed \(ENOTFOUND\)/);
    const dying = async () => new Response(new ReadableStream({ start(c) { c.enqueue(new TextEncoder().encode('<anim')); setTimeout(() => c.error(new TypeError('terminated')), 10); } }));
    const err = await fetchPets(d, { fetchImpl: dying, pinned }).catch((e) => e);
    assert.ok(err instanceof Error);
    assert.equal(err.constructor.name, 'CliError', `a partial download surfaced as ${err.constructor.name}: ${err.message}`);
    assert.equal(fs.existsSync(path.join(d, 'pets', 'esheep64', 'animations.xml')), false);
  });
  test('a response that never ends is bounded (size cap enforced while reading, not after)', async () => {
    const d = dirs();
    let sent = 0;
    const endless = async () => new Response(new ReadableStream({ pull(c) { c.enqueue(new Uint8Array(1024 * 1024)); sent += 1024 * 1024; if (sent > 400 * 1024 * 1024) c.close(); } }));
    await assert.rejects(fetchPets(d, { fetchImpl: endless, pinned }));
    assert.ok(sent <= 64 * 1024 * 1024, `${sent >> 20} MB were read before refusing (cap is 16 MB)`);
  });
});
